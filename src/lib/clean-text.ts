// تمیزسازی خودکار متن انگلیسی از عناوین اخبار ورودی (RSS)
// فقط توکن‌های دارای حروف لاتین حذف می‌شوند؛ متن فارسی و اعداد دست نمی‌خورند.

export function cleanTitle(title: string): string {
  const cleaned = title
    // حذف توکن‌های دارای حروف لاتین (کلمات انگلیسی و ترکیب‌هایی مثل COVID19 و G20)
    .replace(/[A-Za-z0-9\u0660-\u0669\u06F0-\u06F9]*[A-Za-z][A-Za-z0-9\u0660-\u0669\u06F0-\u06F9]*/g, '')
    // حذف پرانتز/کروشه/گیومه خالی باقی‌مانده
    .replace(/\(\s*\)/g, '')
    .replace(/\[\s*\]/g, '')
    .replace(/"\s*"/g, '')
    .replace(/«\s*»/g, '')
    .replace(/\s{2,}/g, ' ')
    // حذف علائم نگارشی اضافه در ابتدا و انتها
    .replace(/^[\s\-–—:؛،,|/\\]+/, '')
    .replace(/[\s\-–—:؛،,|/\\]+$/, '')
    .trim();
  // اگر حرف یا عددی نماند (تیتر کاملاً انگلیسی بود)، اصل را نگه دار تا خبر حذف نشود
  return /[\p{L}\p{N}]/u.test(cleaned) ? cleaned : title.trim();
}
