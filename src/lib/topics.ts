export const categoryMap: Record<string, CategoryDef> = Object.fromEntries(
  menuCategories.map(c => [c.slug, c])
);

export const subcategoryMap: Record<string, { category: string; def: SubCategory }> = Object.fromEntries(
  menuCategories.flatMap(c => c.subcategories.map(sub => [sub.slug, { category: c.slug, def: sub }]))
);

// کلاس‌بندی خودکار یک خبر (بر اساس عنوان و توضیح) به یک زیرموضوع
export function classifyNews(title: string, description = ''): string | null {
  const text = `${title} ${description}`;

  let bestSlug: string | null = null;
  let bestScore = 0;

  for (const cat of menuCategories) {
    for (const sub of cat.subcategories) {
      let score = 0;
      for (const kw of sub.keywords) {
        if (text.includes(kw)) score += 1;
      }
      // امتیاز عنوان مهم‌تر از توضیح است
      for (const kw of sub.keywords) {
        if (title.includes(kw)) score += 1;
      }
      if (score > bestScore) {
        bestScore = score;
        bestSlug = sub.slug;
      }
    }
  }

  return bestSlug;
}
